// Writes supabase/seed.sql from the sample data the apps were built with.
//
//   node supabase/scripts/generate-seed.mjs
//
// seed-data/web-app.json        the web app's catalog facts, timetable and demo households
// seed-data/marketing-site.json the marketing site's copy, journal, jobs and FAQs
// These JSON files were dumped from the apps' local data files before the apps moved to the database.
// They are the seed source now: edit them, not the apps, to change sample data.
//
// When the two sources disagree on a fact (class length, capacity, parking), the web app wins, because its
// booking rules and tests use those numbers. The marketing site adds its own copy fields.
// Logins are not in this file. Run scripts/create-demo-logins.mjs after the seed.

import * as fs from "node:fs"
import * as path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "../..")
const dataDir = path.join(root, "supabase/seed-data")

const read = (name) => JSON.parse(fs.readFileSync(path.join(dataDir, name), "utf8"))
const W = read("web-app.json")
const M = read("marketing-site.json")

// ---------- SQL helpers ----------
const q = (v) => {
  if (v === null || v === undefined) return "null"
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null"
  if (typeof v === "boolean") return v ? "true" : "false"
  return `'${String(v).replace(/'/g, "''")}'`
}
const arr = (xs, type = "text") => (xs == null ? "null" : `array[${xs.map(q).join(", ")}]::${type}[]`)
const js = (v) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`)
const ts = (ms) => (ms == null ? "null" : q(new Date(ms).toISOString()))
const slugify = (s) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")

const out = []
const insert = (table, cols, rows) => {
  if (!rows.length) return
  out.push(`insert into public.${table} (${cols.join(", ")}) values`)
  out.push(`${rows.map((r) => `  (${r.join(", ")})`).join(",\n")};\n`)
}

out.push("-- GENERATED by supabase/scripts/generate-seed.mjs. Do not edit by hand.")
out.push("-- Sample data for a fictional brand. Every name, price, address and person is made up.\n")
out.push("begin;")
out.push("set constraints all deferred;")
out.push(
  "truncate public.visits, public.guest_passes, public.teen_requests, public.message_threads, public.notices,",
  "  public.strikes, public.bookings, public.invoices, public.members, public.households,",
  "  public.class_schedules, public.class_types, public.journal_posts, public.jobs, public.coaches,",
  "  public.faqs, public.site_content, public.price_constants, public.plan_comparison, public.pt_packs,",
  "  public.plans, public.clubs, public.categories, private.demo_seed cascade;\n"
)

// ---------- Categories ----------
const mCat = Object.fromEntries(M.categories.map((c) => [c.id, c]))
insert(
  "categories",
  ["id", "sort", "name", "blurb", "tagline", "lede", "examples", "hero_caption", "intensity_min", "intensity_max"],
  W.categories.map((c, i) => {
    const m = mCat[c.id] ?? {}
    return [q(c.id), i, q(c.name), q(c.blurb), q(m.tagline ?? ""), q(m.lede ?? ""), q(m.examples ?? ""),
      q(m.heroCaption ?? ""), q(m.intensity?.[0] ?? 1), q(m.intensity?.[1] ?? 5)]
  })
)

// ---------- Clubs ----------
const mClub = Object.fromEntries(M.clubs.map((c) => [c.slug, c]))
insert(
  "clubs",
  ["slug", "sort", "legacy_id", "name", "short_name", "city", "neighborhood", "cross_streets", "address", "zip",
    "phone", "tel", "club_type", "type_label", "sqft", "opened", "personality", "intro", "parking", "access_notes",
    "lat", "lng", "scene", "tone", "photo_caption", "amenities", "site_amenities", "signature", "extras", "pool",
    "courts", "has", "kids_club", "recovery", "studios", "typical_weekday", "typical_weekend", "studio_count",
    "demo_miles", "demo_busyness", "map_x", "map_y"],
  W.clubs.map((c, i) => {
    const m = mClub[c.slug]
    if (!m) throw new Error(`marketing site has no club ${c.slug}`)
    return [q(c.slug), i, q(c.id), q(c.name), q(m.short), q(c.city), q(c.neighborhood), q(m.cross), q(c.address),
      q(c.zip), q(c.phone), q(m.tel), q(m.type), q(c.type), q(c.sqft), q(m.opened), q(c.personality), q(m.intro),
      q(m.parking ?? c.parking), q(m.access ?? ""), q(c.lat), q(c.lng), q(c.scene), q(m.tone), q(m.photo ?? c.photo),
      arr(c.amenities), arr(m.amenities), arr(m.signature ?? []), q(m.extras ?? ""), js(c.pool), js(c.courts),
      js(m.has), q(c.kidsClub), q(c.recovery), arr(c.studios), arr(c.typical, "smallint"),
      arr(c.weekend, "smallint"), q(m.studios ?? 0), q(m.miles), q(m.busyness), q(m.map?.x), q(m.map?.y)]
  })
)

// ---------- Coaches: group instructors, personal trainers and marketing coach profiles, merged by name ----------
const coaches = new Map()
const coachFor = (name) => {
  if (!coaches.has(name)) {
    const first = name.split(" ")[0]
    coaches.set(name, { name, first, id: slugify(first), slug: slugify(name), clubs: new Set() })
  }
  return coaches.get(name)
}
for (const i of W.instructors) {
  const c = coachFor(i.name)
  Object.assign(c, { id: i.id, discipline: i.role, years: i.years, teachesClasses: true })
  i.clubs.forEach((x) => c.clubs.add(x))
}
for (const p of W.coaches) {
  const c = coachFor(p.name)
  Object.assign(c, {
    id: c.teachesClasses ? c.id : p.id, slug: p.slug, specialties: p.specialties, tags: p.tags, since: p.since,
    about: p.about, goodFor: p.goodFor, firstSession: p.firstSession, openTimes: p.openTimes, pt: true,
  })
  p.clubs.forEach((x) => c.clubs.add(x))
}
for (const m of M.coaches) {
  const c = coachFor(m.name)
  Object.assign(c, {
    slug: m.slug, credential: m.credential, teaches: m.teaches, favorite: m.favorite, quote: m.quote, tone: m.tone,
    years: c.years ?? m.years, about: c.about ?? m.bio, pt: c.pt || m.pt,
    specialties: c.specialties ?? m.specialties,
  })
  if (!c.about || c.about !== m.bio) c.bio = m.bio
  m.clubs.forEach((x) => c.clubs.add(x))
}
const ids = new Set()
for (const c of coaches.values()) {
  if (ids.has(c.id)) c.id = c.slug
  ids.add(c.id)
}
const coachList = [...coaches.values()]
insert(
  "coaches",
  ["id", "slug", "name", "first_name", "discipline", "credential", "years", "since", "clubs", "teaches_classes",
    "personal_trainer", "specialties", "tags", "teaches", "favorite", "about", "quote", "good_for", "first_session",
    "open_times", "tone"],
  coachList.map((c) => [q(c.id), q(c.slug), q(c.name), q(c.first), q(c.discipline ?? ""), q(c.credential ?? ""),
    q(c.years), q(c.since), arr([...c.clubs]), q(!!c.teachesClasses), q(!!c.pt), arr(c.specialties ?? []),
    arr(c.tags ?? []), arr(c.teaches ?? []), q(c.favorite ?? ""), q(c.about ?? c.bio ?? ""), q(c.quote ?? ""),
    arr(c.goodFor ?? []), arr(c.firstSession ?? []), js(c.openTimes ?? []), q(c.tone ?? "")])
)

// ---------- Class types ----------
const wByName = Object.fromEntries(Object.values(W.classTypes).map((t) => [t.name, t]))
const mByName = Object.fromEntries(M.classTypes.map((t) => [t.name, t]))
const typeRows = []
let sort = 0
for (const m of M.classTypes) {
  const w = wByName[m.name]
  const intensityRange = Array.isArray(m.intensity) ? m.intensity : [m.intensity, m.intensity]
  const cap = w?.capacity ?? (Number((m.group ?? "").match(/\d+/g)?.pop()) || 8)
  typeRows.push([
    q(w?.key ?? m.slug), q(m.slug), sort++, q(m.name), q(m.category), q(w?.duration ?? m.duration),
    q(w?.intensity ?? intensityRange[1]), q(intensityRange[0]), q(intensityRange[1]), q(cap),
    q(w?.unit ?? (m.category === "aqua" ? "lanes" : "spots")), q(w?.firstTimerOk ?? !!m.firstTimer),
    q(w?.teenOk ?? m.category === "youth"), q(w?.minAge ?? 0), q(!!w), q(w?.about ?? m.description ?? ""),
    q(m.blurb ?? ""), arr(w?.bring ?? []), q(w?.equipmentNote ?? ""), q((m.group ?? "").replace(/^Up to \d+( riders)?$/, (_, unit) => `Up to ${cap}${unit ?? ""}`)),
    m.clubs === "all" ? "null" : arr(m.clubs), q(m.pick ?? ""), q(m.gear ?? ""), q(m.caption ?? ""),
  ])
}
for (const w of Object.values(W.classTypes)) {
  if (mByName[w.name]) continue
  typeRows.push([q(w.key), q(slugify(w.name)), sort++, q(w.name), q(w.category), q(w.duration), q(w.intensity),
    q(w.intensity), q(w.intensity), q(w.capacity), q(w.unit), q(w.firstTimerOk), q(w.teenOk), q(w.minAge), "true",
    q(w.about), q(""), arr(w.bring), q(w.equipmentNote ?? ""), q(""), "null", q(""), q(""), q("")])
}
insert(
  "class_types",
  ["key", "slug", "sort", "name", "category_id", "duration", "intensity", "intensity_min", "intensity_max", "capacity",
    "unit", "first_timer_ok", "teen_ok", "min_age", "bookable", "about", "blurb", "bring", "equipment_note",
    "group_label", "club_slugs", "pick", "gear", "caption"],
  typeRows
)

// ---------- Timetable ----------
const sched = []
for (const [club, rows] of Object.entries(W.schedules)) {
  for (const [key, hhmm, days, studio, coachId, intensity] of rows) {
    sched.push([q(club), q(key), q(hhmm), arr([...days].map(Number), "smallint"), q(studio), q(coachId),
      q(intensity ?? null)])
  }
}
insert("class_schedules", ["club_slug", "class_key", "start_time", "days", "studio", "coach_id", "intensity"], sched)

// ---------- Plans and prices ----------
const mPlan = Object.fromEntries(M.plans.map((p) => [p.slug, p]))
insert(
  "plans",
  ["id", "sort", "name", "price", "booking_window_days", "guest_passes", "ribs", "badge", "blurb", "best_for", "perks",
    "features", "compact"],
  Object.values(W.plans).map((p, i) => {
    const m = mPlan[p.id] ?? {}
    return [q(p.id), i, q(p.name), q(p.price), q(p.window), q(p.guestPasses), q(m.ribs ?? 1), q(m.badge ?? null),
      q(p.blurb), q(m.bestFor ?? ""), arr(p.perks), arr(m.features ?? []), arr(m.compact ?? [])]
  })
)
insert("pt_packs", ["sessions", "price"], W.ptPacks.map((p) => [q(p.sessions), q(p.price)]))
insert("plan_comparison", ["sort", "row_label", "trailhead", "ridge", "summit"],
  M.comparison.map((r, i) => [i, q(r.row), ...r.vals.map(q)]))
insert("price_constants", ["key", "amount", "label"], [
  [q("adult_addon"), 39, q("Family add-on, adult")],
  [q("child_addon"), 19, q("Family add-on, child 6 months to 17")],
  [q("pt_single"), 75, q("Personal training, single session")],
  [q("day_pass"), 20, q("Day pass or extra guest pass")],
  [q("enrollment"), 49, q("Enrollment fee ($0 during Fall climb, through Nov 30, 2026)")],
  [q("facility_fee"), 49, q("Annual facility fee, charged in March")],
  [q("freeze_monthly"), 10, q("Freeze, per month for the account")],
])

// ---------- FAQs ----------
const faqRows = []
M.faqs.forEach((f, i) => faqRows.push([q(`site-${f.id}`), q("site"), i, q(f.group ?? ""), q(f.q), q(f.a)]))
M.homeFaq.forEach((f, i) => faqRows.push([q(`home-${f.id}`), q("home"), i, q(""), q(f.q), q(f.a)]))
let n = 0
for (const g of W.faq) {
  for (const f of g.items) faqRows.push([q(`member-${++n}`), q("member"), n, q(g.group), q(f.q), q(f.a)])
}
insert("faqs", ["id", "audience", "sort", "group_name", "question", "answer"], faqRows)

// ---------- Journal, jobs, small lists ----------
insert(
  "journal_posts",
  ["slug", "published_on", "title", "dek", "category", "author_slug", "read_minutes", "tone", "caption", "class_slug",
    "sections"],
  M.journal.map((j) => [q(j.slug), q(j.iso), q(j.title), q(j.dek), q(j.cat), q(j.author), q(j.min), q(j.tone),
    q(j.caption), q(j.cls ?? null), js(j.sections)])
)
insert("jobs", ["slug", "sort", "title", "club", "dept", "job_type", "pay", "details"],
  M.jobs.map((j, i) => {
    const { slug, title, club, dept, type, pay, ...rest } = j
    return [q(slug), i, q(title), q(club), q(dept), q(type), q(pay ?? ""), js(rest)]
  }))
insert("site_content", ["key", "data"], [
  ["testimonials", M.testimonials], ["club_quotes", M.clubQuotes], ["legal_pages", M.legalPages],
  ["first_timer_shelf", M.firstTimerShelf], ["popular_now", M.popularNow], ["amenity_filters", M.amenityFilters],
  ["journal_categories", M.journalCats], ["home_faq_ids", M.faqHome],
].map(([k, v]) => [q(k), js(v)]))

// ---------- Demo households (from the web app's seeded world) ----------
const S = W.state
const memberHh = Object.fromEntries(Object.values(S.members).map((m) => [m.id, m.householdId]))
insert(
  "households",
  ["id", "primary_member_id", "plan_id", "billing_day", "member_since", "status", "freeze_window", "cancel_on", "pending_plan",
    "card", "backup_card", "payment_failed_at", "pt_pack", "pt_intro_left", "guest_passes_bought", "billing_name",
    "billing_address", "receipt_email", "home_club_changed_at", "dismissed", "remind", "opened", "seq"],
  Object.values(S.households).map((h) => [q(h.id), q(h.primaryId), q(h.plan), q(h.billingDay), ts(h.memberSince),
    q(h.status), js(h.freeze), ts(h.cancelOn), js(h.pendingPlan), js(h.card), js(h.backupCard), ts(h.paymentFailedAt),
    js(h.ptPack), q(h.ptIntroLeft), q(h.guestPassesBought), q(h.billingName), q(h.billingAddress),
    q(h.receiptEmail), ts(h.homeClubChangedAt), js(S.dismissed), arr(S.remind), js(S.opened), q(S.seq)])
)
insert(
  "members",
  ["id", "household_id", "role", "first_name", "last_name", "dob", "email", "member_number", "home_club", "parent_id",
    "allergy_notes", "status", "ends_on", "invited_at", "permissions", "pickup", "hue", "paused_until", "streak_weeks",
    "lifetime_visits", "longest_streak", "prefs"],
  Object.values(S.members).map((m) => {
    const st = S.stats[m.id] ?? {}
    return [q(m.id), q(m.householdId), q(m.role), q(m.firstName), q(m.lastName), q(m.dob), q(m.email),
      q(m.memberNumber), q(m.homeClub), q(m.parentId ?? null), q(m.allergyNotes ?? null), q(m.status), ts(m.endsOn),
      ts(m.invitedAt), js(m.permissions), m.pickup ? arr(m.pickup) : "null", q(m.hue), ts(S.pauses[m.id]),
      q(st.streakWeeks ?? 0), q(st.lifetime ?? 0), q(st.longest ?? 0), js(S.prefs[m.id] ?? {})]
  })
)
insert("invoices", ["id", "household_id", "issued_at", "description", "kind", "amount", "status", "lines"],
  Object.values(S.households).flatMap((h) =>
    h.invoices.map((v) => [q(v.id), q(h.id), ts(v.date), q(v.desc), q(v.kind), q(v.amount), q(v.status), js(v.lines)])))
insert(
  "bookings",
  ["id", "household_id", "kind", "member_id", "owner_id", "status", "ref", "club_slug", "starts_at", "ends_at", "title",
    "category_id", "place", "session_id", "spot", "waitlist_position", "hold_expires_at", "resource", "sport",
    "players", "children", "coach_slug", "payment", "feedback_done", "cancelled_at", "no_strike", "created_at"],
  S.bookings.map((b) => [q(b.id), q(memberHh[b.ownerId]), q(b.kind), q(b.memberId), q(b.ownerId), q(b.status),
    q(b.ref), q(b.clubSlug), ts(b.start), ts(b.end), q(b.title), q(b.category), q(b.place), q(b.sessionId ?? null),
    q(b.spot ?? null), q(b.position ?? null), ts(b.holdExpiresAt), q(b.resource ?? null), q(b.sport ?? null),
    js(b.players), b.children ? arr(b.children) : "null", q(b.coachSlug ?? null), q(b.payment ?? null),
    q(!!b.feedbackDone), ts(b.cancelledAt), q(!!b.noStrike), ts(b.createdAt)])
)
insert("strikes", ["id", "household_id", "member_id", "at", "booking_id", "title"],
  S.strikes.map((s) => [q(s.id), q(memberHh[s.memberId]), q(s.memberId), ts(s.at), q(s.bookingId ?? null), q(s.title)]))
insert(
  "notices",
  ["id", "household_id", "member_id", "type", "title", "body", "at", "read_at", "needs_action", "action_label",
    "booking_id", "request_id", "thread_id", "filter", "done"],
  S.notices.map((x) => [q(x.id), q(memberHh[x.memberId]), q(x.memberId), q(x.type), q(x.title), q(x.body), ts(x.at),
    ts(x.readAt), q(!!x.needsAction), q(x.actionLabel ?? null), q(x.bookingId ?? null), q(x.requestId ?? null),
    q(x.threadId ?? null), q(x.filter), q(x.done ?? null)])
)
insert("message_threads", ["id", "household_id", "member_id", "with_name", "subject", "messages"],
  S.threads.map((t) => [q(t.id), q(memberHh[t.memberId]), q(t.memberId), q(t.with), q(t.subject), js(t.messages)]))
insert(
  "teen_requests",
  ["id", "household_id", "teen_id", "parent_id", "session_id", "title", "note", "at", "status", "expires_at"],
  S.requests.map((r) => [q(r.id), q(memberHh[r.teenId]), q(r.teenId), q(r.parentId), q(r.sessionId ?? null),
    q(r.title), q(r.note ?? null), ts(r.at), q(r.status), ts(r.expiresAt)])
)
insert(
  "guest_passes",
  ["id", "household_id", "guest_name", "contact", "club_slug", "visit_date", "valid_until", "status", "bought",
    "used_on", "message", "sent_at"],
  S.guestPasses.map((g) => [q(g.id), q(g.householdId), q(g.guestName), q(g.contact), q(g.clubSlug), ts(g.visitDate),
    ts(g.validUntil), q(g.status), q(g.bought), ts(g.usedOn), q(g.message ?? null), ts(g.sentAt)])
)
insert("visits", ["household_id", "member_id", "club_slug", "at", "category_id"],
  S.visits.map((v) => [q(memberHh[v.memberId]), q(v.memberId), q(v.clubSlug), ts(v.at), q(v.category ?? null)]))

// ---------- Snapshot for reset_demo_household() ----------
out.push("-- Snapshot of each household, so a member can put the demo back to this state.")
out.push("insert into private.demo_seed (household_id, table_name, rows)")
out.push("select id, 'households', jsonb_agg(to_jsonb(h)) from public.households h group by id")
for (const t of ["members", "invoices", "bookings", "strikes", "notices", "message_threads", "teen_requests",
  "guest_passes", "visits"]) {
  out.push(`union all select household_id, '${t}', jsonb_agg(to_jsonb(x)) from public.${t} x group by household_id`)
}
out.push(";\n")
out.push("commit;")

fs.writeFileSync(path.join(root, "supabase/seed.sql"), `${out.join("\n")}\n`)
console.log(
  `seed.sql: ${W.clubs.length} clubs, ${coachList.length} coaches, ${typeRows.length} class types, ` +
    `${sched.length} timetable rows, ${Object.keys(S.households).length} households, ` +
    `${Object.keys(S.members).length} members, ${S.bookings.length} bookings`
)
